CELL_W = 5.0
CELL_H = 7.0


def stroke_text(s, x, y, h=5.0, anchor='lb', spacing=0.42):
    """Return a list of polylines (lists of (x, y)) drawing `s`.

    anchor: two chars, horizontal l/c/r + vertical b/m/t.
    'O/' is written in source as the token '@' -> diameter symbol.
    """
    sc = h / CELL_H
    adv = (CELL_W + CELL_W * spacing) * sc
    chars = []
    i = 0
    while i < len(s):
        c = s[i].upper()
        if c == '@':
            c = 'O/'
        chars.append(c)
        i += 1
    width = adv * len(chars) - CELL_W * spacing * sc

    if anchor[0] == 'c':
        x -= width / 2.0
    elif anchor[0] == 'r':
        x -= width
    if anchor[1] == 'm':
        y -= h / 2.0
    elif anchor[1] == 't':
        y -= h

    out = []
    cx = x
    for c in chars:
        for seg in G.get(c, []):
            out.append([(cx + px * sc, y + py * sc) for (px, py) in seg])
        cx += adv
    return out


def text_width(s, h=5.0, spacing=0.42):
    sc = h / CELL_H
    n = len(s)
    return (CELL_W + CELL_W * spacing) * sc * n - CELL_W * spacing * sc
